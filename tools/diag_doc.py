"""Regenerate the node tables in docs/DIAGNOSTICS.md from docs/diagnostics_graph.json.

The JSON is written by the VS Code integration test 'every feature keeps its diagnostic nodes'
(npx vscode-test --label unit), straight from buildGraph(), so the document cannot drift from the
code. Run after that test:  python tools/diag_doc.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.join(HERE, "..", "docs")
GRAPH = os.path.join(DOCS, "diagnostics_graph.json")
DOC = os.path.join(DOCS, "DIAGNOSTICS.md")

LAYERS = [
    ("laptop", "Laptop"),
    ("vscode", "VS Code"),
    ("network", "Network"),
    ("account", "Accounts"),
    ("grid-login", "Grid login node"),
    ("grid-slurm", "Grid jobs"),
    ("grid-node", "Compute node and container"),
]


def cell(s):
    return str(s or "").replace("|", "\\|").replace("\n", " ").strip()


def render(g):
    nodes = g["nodes"]
    out = []
    n_rep = sum(1 for n in nodes if n["autoRepair"])
    out.append(f"{len(nodes)} nodes, {n_rep} with an automatic repair. Generated by `tools/diag_doc.py`.\n")
    for key, title in LAYERS:
        layer = [n for n in nodes if n["layer"] == key]
        if not layer:
            continue
        out.append(f"### {title}\n")
        out.append("| Node | Depends on | Assumes | Repair | If it fails | Future risk |")
        out.append("|---|---|---|---|---|---|")
        for n in layer:
            dep = ", ".join(f"`{d}`" for d in n["dependsOn"]) or "none"
            rep = "automatic" if n["autoRepair"] else "by hand"
            out.append(f"| `{n['id']}` {cell(n['title'])} | {dep} | {cell(n['assumption'])} | {rep} | {cell(n['manualFix'])} | {cell(n['futureRisk'])} |")
        out.append("")
    other = [n for n in nodes if n["layer"] not in {k for k, _ in LAYERS}]
    if other:
        out.append("### Other\n")
        for n in other:
            out.append(f"- `{n['id']}` {cell(n['title'])}")
        out.append("")
    out.append("### Features and the nodes they must keep\n")
    out.append("| Feature | Nodes |")
    out.append("|---|---|")
    for f, ids in g["features"].items():
        out.append(f"| {f.replace('_', ' ')} | {', '.join(f'`{i}`' for i in ids)} |")
    out.append("")
    return "\n".join(out)


def main():
    g = json.load(open(GRAPH, encoding="utf-8"))
    doc = open(DOC, encoding="utf-8").read()
    block = "<!-- graph:begin -->\n" + render(g) + "<!-- graph:end -->"
    doc2 = re.sub(r"<!-- graph:begin -->.*?<!-- graph:end -->", lambda _m: block, doc, flags=re.S)
    assert doc2 != doc or block in doc, "markers missing in DIAGNOSTICS.md"
    open(DOC, "w", encoding="utf-8", newline="\n").write(doc2)
    print(f"{len(g['nodes'])} nodes written to {os.path.relpath(DOC)}")


if __name__ == "__main__":
    main()
